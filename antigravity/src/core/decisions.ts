import { randomBytes } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { appendJsonlLine, atomicWriteFile, isSingleLine } from "./fs-utils.js";

export type Decision = {
  readonly id: string;
  readonly question: string;
  readonly source: string;
  readonly askedAt: string;
  readonly lane?: string;
  readonly thread?: string;
  readonly options: readonly string[];
  readonly recommend?: number;
  readonly worklog?: string;
  readonly message?: string;
  readonly answeredAt?: string;
  readonly answer?: string;
  readonly option?: number;
  readonly answerSource?: string;
  readonly withdrawnAt?: string;
  readonly reason?: string;
};

export type DecisionAsk = {
  readonly question: string;
  readonly source: string;
  readonly lane?: string;
  readonly thread?: string;
  readonly options?: readonly string[];
  readonly recommend?: number;
  readonly worklog?: string;
  readonly message?: string;
};

type Stamp = { readonly id: string; readonly at: string; readonly n: string };
type DecisionEvent =
  | (Stamp & { readonly op: "ask" } & DecisionAsk)
  | (Stamp & { readonly op: "posted"; readonly message: string })
  | (Stamp & { readonly op: "answer"; readonly answer: string; readonly source: string; readonly option?: number })
  | (Stamp & { readonly op: "withdraw"; readonly reason: string });

export type DecisionRead = {
  readonly items: Decision[];
  readonly problems: string[];
  readonly warnings: string[];
};

export class DecisionError extends Error {}

export const MAX_OPTIONS = 9;
const ID = /^[0-9a-f]{8}$/;
const RECORD_START = '{"op":"';
export const DECISIONS_MARKER = "<!-- Generated by cataly decisions. Do not hand-edit. -->";

const inRange = (value: unknown, max: number): value is number =>
  typeof value === "number" && Number.isInteger(value) && value >= 1 && value <= max;

const isoTime = (value: unknown): value is string =>
  typeof value === "string" && Number.isFinite(Date.parse(value)) && new Date(value).toISOString() === value;

const isTorn = (line: string): boolean => line.startsWith(RECORD_START) || RECORD_START.startsWith(line);

export const settled = (d: Decision): "answered" | "withdrawn" | undefined =>
  d.answeredAt !== undefined ? "answered" : d.withdrawnAt !== undefined ? "withdrawn" : undefined;

const parseEvent = (value: unknown): DecisionEvent => {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new DecisionError("decision record must be a JSON object");
  }
  const record = value as Record<string, unknown>;
  if (typeof record["id"] !== "string" || !ID.test(record["id"])) {
    throw new DecisionError('decision field "id" must be 8 lowercase hex digits');
  }
  if (!isoTime(record["at"])) {
    throw new DecisionError('decision field "at" must be an ISO timestamp');
  }
  if (typeof record["n"] !== "string" || !ID.test(record["n"])) {
    throw new DecisionError('decision field "n" must be 8 lowercase hex digits');
  }
  const op = record["op"];
  if (op === "ask") {
    if (!isSingleLine(record["question"], 1000)) throw new DecisionError("question must be a single line (max 1000)");
    if (!isSingleLine(record["source"], 400)) throw new DecisionError("source must be a single line (max 400)");
    for (const ref of ["lane", "thread", "message"]) {
      if (record[ref] !== undefined) {
        if (!isSingleLine(record[ref], 400) || /\s/.test(String(record[ref]))) {
          throw new DecisionError(`decision field "${ref}" must be a single token without spaces`);
        }
      }
    }
    if (record["worklog"] !== undefined && !ID.test(String(record["worklog"]))) {
      throw new DecisionError("worklog must be 8 lowercase hex digits");
    }
    const options = record["options"];
    if (
      options !== undefined &&
      (!Array.isArray(options) || !inRange(options.length, MAX_OPTIONS) || !options.every((o) => isSingleLine(o, 200)))
    ) {
      throw new DecisionError(`options must hold 1 to ${MAX_OPTIONS} single-line entries`);
    }
    const count = Array.isArray(options) ? options.length : 0;
    if (record["recommend"] !== undefined && !inRange(record["recommend"], count)) {
      throw new DecisionError(count ? `recommend must be 1..${count}` : "recommend requires options");
    }
  } else if (op === "posted") {
    if (!isSingleLine(record["message"], 400) || /\s/.test(String(record["message"]))) {
      throw new DecisionError("message must be a single reference token without spaces");
    }
  } else if (op === "answer") {
    if (!isSingleLine(record["answer"], 1000)) throw new DecisionError("answer must be a single line (max 1000)");
    if (!isSingleLine(record["source"], 400)) throw new DecisionError("source must be a single line (max 400)");
    if (record["option"] !== undefined && !inRange(record["option"], MAX_OPTIONS)) {
      throw new DecisionError(`option must be 1..${MAX_OPTIONS}`);
    }
  } else if (op === "withdraw") {
    if (!isSingleLine(record["reason"], 1000)) throw new DecisionError("reason must be a single line (max 1000)");
  } else {
    throw new DecisionError('decision field "op" must be ask, posted, answer or withdraw');
  }
  return record as DecisionEvent;
};

export function renderDecisionsDigest(openDecisions: readonly Decision[]): string {
  if (openDecisions.length === 0) return "No open decisions waiting on the owner.";
  const lines: string[] = [];
  for (const d of openDecisions) {
    const scope = [d.lane ? `lane:${d.lane}` : "", d.worklog ? `worklog:${d.worklog}` : ""].filter(Boolean).join(" ");
    lines.push(`[${d.id}] ${d.question}${scope ? ` (${scope})` : ""}`);
    d.options.forEach((opt, i) => {
      const n = i + 1;
      const rec = d.recommend === n ? " (recommended)" : "";
      lines.push(`  ${n}. ${opt}${rec}`);
    });
  }
  return lines.join("\n");
}

function renderDecisionsMarkdown(items: readonly Decision[]): string {
  const open = items.filter((d) => !settled(d));
  const closed = items.filter((d) => settled(d));
  const lines: string[] = [DECISIONS_MARKER, "", "# Cataly Decisions", "", `## Waiting on Owner (${open.length})`, ""];
  if (open.length === 0) {
    lines.push("_No pending decisions._", "");
  } else {
    for (const d of open) {
      lines.push(`### [${d.id}] ${d.question}`);
      lines.push(`- **Asked**: ${d.askedAt} | **Source**: ${d.source}`);
      if (d.lane) lines.push(`- **Lane**: ${d.lane}`);
      if (d.thread) lines.push(`- **Thread**: ${d.thread}`);
      if (d.message) lines.push(`- **Message Ref**: ${d.message}`);
      if (d.options.length > 0) {
        lines.push("- **Options**:");
        d.options.forEach((opt, idx) => {
          const n = idx + 1;
          lines.push(`  ${n}. ${opt}${d.recommend === n ? " *(recommended)*" : ""}`);
        });
      }
      lines.push("");
    }
  }
  if (closed.length > 0) {
    lines.push(`## Settled (${Math.min(closed.length, 20)} of ${closed.length})`, "");
    for (const d of closed.slice(-20).reverse()) {
      if (d.answeredAt) {
        const optPart = d.option !== undefined ? ` [option ${d.option}]` : "";
        lines.push(`- [${d.id}] ${d.question} -> **Answered**${optPart}: ${d.answer}`);
      } else {
        lines.push(`- [${d.id}] ${d.question} -> **Withdrawn**: ${d.reason}`);
      }
    }
    lines.push("");
  }
  return lines.join("\n");
}

export class Decisions {
  readonly path: string;
  readonly markdownPath: string;

  constructor(readonly stateDir: string) {
    this.path = join(stateDir, "decisions.jsonl");
    this.markdownPath = join(stateDir, "decisions.md");
  }

  read(): DecisionRead {
    return this.fold(existsSync(this.path) ? readFileSync(this.path, "utf8") : "");
  }

  open(): Decision[] {
    return this.read().items.filter((d) => !settled(d));
  }

  ask(input: DecisionAsk, now = Date.now()): Decision {
    const known = new Set(this.read().items.map((item) => item.id));
    let id = randomBytes(4).toString("hex");
    while (known.has(id)) id = randomBytes(4).toString("hex");
    const event: DecisionEvent = {
      op: "ask",
      id,
      at: new Date(now).toISOString(),
      n: randomBytes(4).toString("hex"),
      question: input.question.trim(),
      source: input.source.trim(),
      ...(input.lane ? { lane: input.lane.trim() } : {}),
      ...(input.thread ? { thread: input.thread.trim() } : {}),
      ...(input.options && input.options.length > 0 ? { options: input.options.map((o) => o.trim()) } : {}),
      ...(input.recommend !== undefined ? { recommend: input.recommend } : {}),
      ...(input.worklog ? { worklog: input.worklog.trim() } : {}),
      ...(input.message ? { message: input.message.trim() } : {}),
    };
    return this.write(event);
  }

  posted(id: string, message: string, now = Date.now()): Decision {
    this.requireOpen(id);
    return this.write({
      op: "posted",
      id,
      at: new Date(now).toISOString(),
      n: randomBytes(4).toString("hex"),
      message: message.trim(),
    });
  }

  match(messageRef: string): Decision | null {
    const target = messageRef.trim();
    if (!target) return null;
    const hits = this.open().filter((d) => d.message === target);
    return hits.length === 1 ? (hits[0] ?? null) : null;
  }

  answer(id: string, answer: string, source: string, option?: number, now = Date.now()): Decision {
    const item = this.requireOpen(id);
    if (option !== undefined) {
      if (item.options.length === 0) throw new DecisionError(`decision ${id} has no numbered options`);
      if (!inRange(option, item.options.length)) {
        throw new DecisionError(`option must be between 1 and ${item.options.length}`);
      }
    }
    return this.write({
      op: "answer",
      id,
      at: new Date(now).toISOString(),
      n: randomBytes(4).toString("hex"),
      answer: answer.trim(),
      source: source.trim(),
      ...(option !== undefined ? { option } : {}),
    });
  }

  withdraw(id: string, reason: string, now = Date.now()): Decision {
    this.requireOpen(id);
    return this.write({
      op: "withdraw",
      id,
      at: new Date(now).toISOString(),
      n: randomBytes(4).toString("hex"),
      reason: reason.trim(),
    });
  }

  digest(): string {
    return renderDecisionsDigest(this.open());
  }

  private requireOpen(id: string): Decision {
    const item = this.read().items.find((d) => d.id === id);
    if (!item) throw new DecisionError(`decision not found: ${id}`);
    const state = settled(item);
    if (state) throw new DecisionError(`decision ${id} is already ${state}`);
    return item;
  }

  private fold(text: string): DecisionRead {
    const items = new Map<string, Decision>();
    const problems: string[] = [];
    const warnings: string[] = [];
    for (const [index, line] of text.split("\n").entries()) {
      if (!line.trim()) continue;
      let parsed: unknown;
      try {
        parsed = JSON.parse(line);
      } catch (error) {
        if (!(error instanceof SyntaxError)) throw error;
        if (!isTorn(line)) problems.push(`${this.path}:${index + 1}: ${error.message}`);
        continue;
      }
      try {
        const event = parseEvent(parsed);
        const cur = items.get(event.id);
        if (event.op === "ask") {
          if (cur) throw new DecisionError(`decision ${event.id} was already asked`);
          items.set(event.id, {
            id: event.id,
            question: event.question,
            source: event.source,
            askedAt: event.at,
            options: event.options ?? [],
            ...(event.lane ? { lane: event.lane } : {}),
            ...(event.thread ? { thread: event.thread } : {}),
            ...(event.recommend !== undefined ? { recommend: event.recommend } : {}),
            ...(event.worklog ? { worklog: event.worklog } : {}),
            ...(event.message ? { message: event.message } : {}),
          });
          continue;
        }
        if (!cur) throw new DecisionError(`decision ${event.id} was never asked`);
        if (settled(cur)) {
          warnings.push(`${this.path}:${index + 1}: decision ${event.id} already settled; ${event.op} ignored`);
          continue;
        }
        if (event.op === "posted") {
          items.set(event.id, { ...cur, message: event.message });
        } else if (event.op === "answer") {
          items.set(event.id, {
            ...cur,
            answeredAt: event.at,
            answer: event.answer,
            answerSource: event.source,
            ...(event.option !== undefined ? { option: event.option } : {}),
          });
        } else {
          items.set(event.id, { ...cur, withdrawnAt: event.at, reason: event.reason });
        }
      } catch (error) {
        if (!(error instanceof DecisionError)) throw error;
        problems.push(`${this.path}:${index + 1}: ${error.message}`);
      }
    }
    return { items: [...items.values()], problems, warnings };
  }

  private write(event: DecisionEvent): Decision {
    parseEvent(event);
    appendJsonlLine(this.path, event);
    const read = this.read();
    atomicWriteFile(this.markdownPath, renderDecisionsMarkdown(read.items));
    const item = read.items.find((d) => d.id === event.id);
    if (!item) throw new DecisionError(`decision ${event.id} did not read back`);
    return item;
  }
}
