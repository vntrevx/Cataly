import { randomBytes } from "node:crypto";
import { existsSync, readFileSync } from "node:fs";
import { join } from "node:path";
import { appendJsonlLine, atomicWriteFile, isSingleLine } from "./fs-utils.js";

export type WorklogItem = {
  readonly id: string;
  readonly title: string;
  readonly source: string;
  readonly openedAt: string;
  readonly next?: string;
  readonly notes: readonly { readonly at: string; readonly text: string }[];
  readonly closedAt?: string;
  readonly result?: string;
};

type WorklogEvent =
  | { readonly op: "add"; readonly id: string; readonly at: string; readonly title: string; readonly source: string }
  | { readonly op: "next"; readonly id: string; readonly at: string; readonly text: string }
  | { readonly op: "note"; readonly id: string; readonly at: string; readonly text: string }
  | { readonly op: "close"; readonly id: string; readonly at: string; readonly result: string };

export type WorklogRead = {
  readonly items: WorklogItem[];
  readonly problems: string[];
  readonly warnings: string[];
};

export class WorklogError extends Error {}

const ID = /^[0-9a-f]{8}$/;
const RECORD_START = '{"op":"';
export const WORKLOG_MARKER = "<!-- Generated by cataly worklog. Do not hand-edit. -->";

const isoTime = (value: unknown): value is string =>
  typeof value === "string" && Number.isFinite(Date.parse(value)) && new Date(value).toISOString() === value;

const isTorn = (line: string): boolean => line.startsWith(RECORD_START) || RECORD_START.startsWith(line);

const parseEvent = (value: unknown): WorklogEvent => {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    throw new WorklogError("worklog record must be a JSON object");
  }
  const record = value as Record<string, unknown>;
  if (typeof record["id"] !== "string" || !ID.test(record["id"])) {
    throw new WorklogError('worklog field "id" must be 8 lowercase hex digits');
  }
  if (!isoTime(record["at"])) {
    throw new WorklogError('worklog field "at" must be an ISO timestamp');
  }
  const fields: Record<string, Record<string, number>> = {
    add: { title: 200, source: 400 },
    next: { text: 1000 },
    note: { text: 1000 },
    close: { result: 1000 },
  };
  const op = record["op"];
  const wanted = typeof op === "string" ? fields[op] : undefined;
  if (!wanted) throw new WorklogError('worklog field "op" must be add, next, note or close');
  for (const [name, max] of Object.entries(wanted)) {
    if (!isSingleLine(record[name], max)) {
      throw new WorklogError(`worklog field "${name}" must be one nonempty line of at most ${max} characters`);
    }
  }
  return record as WorklogEvent;
};

export function renderWorklogMarkdown(items: readonly WorklogItem[]): string {
  const open = items.filter((item) => item.closedAt === undefined);
  const closed = items.filter((item) => item.closedAt !== undefined);
  const lines: string[] = [WORKLOG_MARKER, "", "# Cataly Worklog", ""];

  lines.push(`## Open (${open.length})`, "");
  if (open.length === 0) {
    lines.push("_No open items._", "");
  } else {
    for (const item of open) {
      lines.push(`### [${item.id}] ${item.title}`);
      lines.push(`- **Source**: ${item.source}`);
      lines.push(`- **Opened**: ${item.openedAt}`);
      lines.push(`- **Next**: ${item.next ?? "(not set)"}`);
      if (item.notes.length > 0) {
        lines.push("- **Notes**:");
        for (const n of item.notes) {
          lines.push(`  - ${n.at}: ${n.text}`);
        }
      }
      lines.push("");
    }
  }

  if (closed.length > 0) {
    lines.push(`## Recently Closed (${Math.min(closed.length, 20)} of ${closed.length})`, "");
    for (const item of closed.slice(-20).reverse()) {
      lines.push(`- [${item.id}] **${item.title}** (${item.closedAt}): ${item.result ?? ""}`);
    }
    lines.push("");
  }

  return lines.join("\n");
}

export class Worklog {
  readonly path: string;
  readonly markdownPath: string;

  constructor(readonly stateDir: string) {
    this.path = join(stateDir, "worklog.jsonl");
    this.markdownPath = join(stateDir, "worklog.md");
  }

  read(): WorklogRead {
    return this.fold(existsSync(this.path) ? readFileSync(this.path, "utf8") : "");
  }

  open(): WorklogItem[] {
    return this.read().items.filter((item) => item.closedAt === undefined);
  }

  add(title: string, source: string, now = Date.now()): WorklogItem {
    const known = new Set(this.read().items.map((item) => item.id));
    let id = randomBytes(4).toString("hex");
    while (known.has(id)) id = randomBytes(4).toString("hex");
    return this.write({ op: "add", id, at: new Date(now).toISOString(), title: title.trim(), source: source.trim() });
  }

  next(id: string, text: string, now = Date.now()): WorklogItem {
    this.requireOpen(id);
    return this.write({ op: "next", id, at: new Date(now).toISOString(), text: text.trim() });
  }

  note(id: string, text: string, now = Date.now()): WorklogItem {
    this.requireOpen(id);
    return this.write({ op: "note", id, at: new Date(now).toISOString(), text: text.trim() });
  }

  close(id: string, result: string, now = Date.now()): WorklogItem {
    this.requireOpen(id);
    return this.write({ op: "close", id, at: new Date(now).toISOString(), result: result.trim() });
  }

  private requireOpen(id: string): WorklogItem {
    const item = this.read().items.find((candidate) => candidate.id === id);
    if (!item) throw new WorklogError(`worklog item not found: ${id}`);
    if (item.closedAt !== undefined)
      throw new WorklogError(`worklog item ${id} is already closed: ${item.result ?? ""}`);
    return item;
  }

  private fold(text: string): WorklogRead {
    const items = new Map<string, WorklogItem>();
    const problems: string[] = [];
    const warnings: string[] = [];
    for (const [index, line] of text.split("\n").entries()) {
      if (!line.trim()) continue;
      let value: unknown;
      try {
        value = JSON.parse(line);
      } catch (error) {
        if (!(error instanceof SyntaxError)) throw error;
        if (!isTorn(line)) problems.push(`${this.path}:${index + 1}: ${error.message}`);
        continue;
      }
      try {
        const event = parseEvent(value);
        const item = items.get(event.id);
        if (event.op === "add") {
          if (item) throw new WorklogError(`worklog item ${event.id} was already added`);
          items.set(event.id, {
            id: event.id,
            title: event.title,
            source: event.source,
            openedAt: event.at,
            notes: [],
          });
          continue;
        }
        if (!item) throw new WorklogError(`worklog item ${event.id} was never added`);
        if (item.closedAt !== undefined && event.op === "close") continue;
        if (item.closedAt !== undefined) {
          warnings.push(`${this.path}:${index + 1}: worklog item ${event.id} was already closed; ${event.op} ignored`);
          continue;
        }
        if (event.op === "next") items.set(event.id, { ...item, next: event.text });
        else if (event.op === "note") {
          items.set(event.id, { ...item, notes: [...item.notes, { at: event.at, text: event.text }] });
        } else {
          items.set(event.id, { ...item, closedAt: event.at, result: event.result });
        }
      } catch (error) {
        if (!(error instanceof WorklogError)) throw error;
        problems.push(`${this.path}:${index + 1}: ${error.message}`);
      }
    }
    return { items: [...items.values()], problems, warnings };
  }

  private write(event: WorklogEvent): WorklogItem {
    parseEvent(event);
    appendJsonlLine(this.path, event);
    const read = this.read();
    atomicWriteFile(this.markdownPath, renderWorklogMarkdown(read.items));
    const item = read.items.find((candidate) => candidate.id === event.id);
    if (!item) throw new WorklogError(`worklog item ${event.id} did not read back`);
    return item;
  }
}
